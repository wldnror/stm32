"""Generate dependency-free C drawing assets from the existing OLED renderer."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from boot_display import FONT, SH1107_INIT, static_frame


def build():
    lines = ['/* Generated by native/build_assets.py; do not edit. */',
             'static const unsigned char oled_init[] = {' + ','.join(map(str, (0, *SH1107_INIT))) + '};',
             'static const unsigned char base_frame[8192] = {']
    frame = static_frame(0, '')
    lines.extend(','.join(map(str, frame[i:i+128])) + ',' for i in range(0, len(frame), 128))
    lines += ['};', 'static const unsigned char glyphs[128][5] = {']
    lines.extend('[%d]={%s},' % (ord(char), ','.join(map(str, values)))
                 for char, values in sorted(FONT.items()))
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    Path(__file__).with_name('boot_assets.h').write_text(build())
